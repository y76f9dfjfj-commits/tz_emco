"""Входной фильтр телеметрии: отсев дублей и сообщений, нарушающих порядок."""

from __future__ import annotations


def is_in_order(last_ts: int | None, ts: int) -> bool:
    """Проверяет, нужно ли учитывать сообщение машины по его времени.

    Правило ТЗ «Порядок и дубли»: сообщение с ts, не превышающим последний
    учтённый ts той же машины, игнорируется (дубли и нарушение порядка);
    опоздавшее сообщение с более новым ts учитывается.

    Args:
        last_ts: Последний учтённый ts машины или None, если сообщений ещё не было.
        ts: Время пришедшего сообщения, секунды epoch.

    Returns:
        True, если сообщение нужно учесть.
    """
    return last_ts is None or ts > last_ts
